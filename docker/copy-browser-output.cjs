'use strict';
const fs = require('node:fs');
const path = require('node:path');
const angular = JSON.parse(fs.readFileSync('angular.json', 'utf8'));
const apps = Object.entries(angular.projects).filter(([, p]) => p.projectType === 'application');
if (apps.length !== 1) throw new Error('Esperado um projeto application no angular.json.');
const [name, project] = apps[0];
const builder = project.architect?.esbuild || project.targets?.esbuild;
if (!builder) throw new Error('Target esbuild ausente.');
const config = builder.configurations?.production?.outputPath ?? builder.options?.outputPath ?? `dist/${name}`;
const base = typeof config === 'string' ? config : config.base;
const browser = typeof config === 'string' ? 'browser' : (config.browser ?? 'browser');
const candidates = [path.resolve(base, browser), path.resolve(base)];
const output = candidates.find(dir => fs.existsSync(path.join(dir, 'remoteEntry.json')) && fs.existsSync(path.join(dir, 'index.html')));
if (!output) throw new Error(`Build incompleto: index.html/remoteEntry.json ausentes em ${candidates.join(', ')}`);
JSON.parse(fs.readFileSync(path.join(output, 'remoteEntry.json'), 'utf8'));
fs.mkdirSync('/opt/web-dist', { recursive: true });
fs.cpSync(output, '/opt/web-dist', { recursive: true });
console.log(`Artefatos preparados: ${output}`);
